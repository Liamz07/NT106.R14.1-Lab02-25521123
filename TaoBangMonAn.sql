CREATE TABLE NguoiDung (
    IDNCC INTEGER PRIMARY KEY AUTOINCREMENT,
    HoVaTen TEXT NOT NULL,
    QuyenHan TEXT
);

CREATE TABLE MonAn (
    IDMA INTEGER PRIMARY KEY AUTOINCREMENT,
    TenMonAn TEXT NOT NULL,
    HinhAnh TEXT,
    IDNCC INTEGER,
    FOREIGN KEY (IDNCC) REFERENCES NguoiDung(IDNCC)
);